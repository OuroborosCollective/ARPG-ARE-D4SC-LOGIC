"""Write Assets/Scripts/Core/CourtLayout.cs from the baked station grid (station_grid.py).

usage: python3 -I station_layout_cs.py <station-grid.json> <CourtLayout.cs> <spawn x> <spawn z> <exit x> <exit z>   (metres)
"""
import json
import sys

grid = json.load(open(sys.argv[1]))
out = sys.argv[2]
spawn = (float(sys.argv[3]), float(sys.argv[4]))
exit_ = (float(sys.argv[5]), float(sys.argv[6]))
r = grid["report"]


def mm(v):
    return int(round(v * 1000))


walk = ",\n".join('            "%s"' % row for row in grid["walk"])
heights = ",\n".join('            "%s"' % row for row in grid["heights"])
source = '''using System;
using System.Globalization;

namespace AreArpg.Core
{
    /// <summary>
    /// Aschenwacht between the old crypt and the village (owner decision 2026-11-25): the desecrated forecourt, the connector
    /// and the bell court as one walkable place. Generated by Tools/Art/aschenwacht/station_layout_cs.py from the grid that
    /// station_grid.py bakes from the places' own collision and scenery; do not edit by hand.
    ///
    /// Frame: millimetres, x east, z north; the crypt portal lies in the south, the bell court in the north. Walk rows are
    /// run-length encoded per row of 250 mm cells from the southern edge ("12#40." = 12 blocked, 40 free), the wanderer's
    /// radius is already part of every obstacle. Height rows hold one character per 500 mm cell in steps of 50 mm above
    /// <see cref="HeightBaseMm"/>; heights only place the presentation, the rules stay two-dimensional.
    /// </summary>
    public static class CourtLayout
    {
        public const long CellMm = 250L, HeightCellMm = 500L, HeightStepMm = 50L;
        public const long MinXmm = %(min_x)dL, MinZmm = %(min_z)dL, HeightBaseMm = %(base)dL;
        public const int Columns = %(cols)d, RowCount = %(rows)d, HeightColumns = %(hcols)d, HeightRowCount = %(hrows)d;
        /// <summary>In front of the crypt portal, where the wanderer steps out of the old crypt.</summary>
        public const long SpawnXmm = %(sx)dL, SpawnZmm = %(sz)dL;
        /// <summary>At the door of the bell tower: from here the pilgrim path leads down to the village.</summary>
        public const long ExitXmm = %(ex)dL, ExitZmm = %(ez)dL;
        /// <summary>North of this line lies the bell court; south of it the desecrated forecourt.</summary>
        public const long BellCourtZmm = 46000L;

        private static readonly bool[] Walk;
        private static readonly byte[] Height;

        // The static constructor runs after every field initialiser, so the row tables below exist when they are decoded.
        static CourtLayout()
        {
            Walk = DecodeWalk();
            Height = DecodeHeights();
        }

        public static bool CanStand(long x, long z)
        {
            long column = FloorDiv(x - MinXmm, CellMm), row = FloorDiv(z - MinZmm, CellMm);
            if (column < 0 || row < 0 || column >= Columns || row >= RowCount) return false;
            return Walk[row * Columns + column];
        }

        /// <summary>Ground height in millimetres, bilinear between the centres of the 500 mm height cells.</summary>
        public static long HeightMm(long x, long z)
        {
            long fx = x - MinXmm - HeightCellMm / 2, fz = z - MinZmm - HeightCellMm / 2;
            long cx = FloorDiv(fx, HeightCellMm), cz = FloorDiv(fz, HeightCellMm);
            long wx = fx - cx * HeightCellMm, wz = fz - cz * HeightCellMm;
            long a = Sample(cx, cz), b = Sample(cx + 1, cz), c = Sample(cx, cz + 1), d = Sample(cx + 1, cz + 1);
            long south = a * (HeightCellMm - wx) + b * wx, north = c * (HeightCellMm - wx) + d * wx;
            return HeightBaseMm + (south * (HeightCellMm - wz) + north * wz) / (HeightCellMm * HeightCellMm);
        }

        /// <summary>
        /// The shortest way over free cells (four neighbours, so no corner is cut) from one point to another, as cell centres in
        /// millimetres, x and z alternating; empty when either end is blocked or no way exists. Breadth-first in a fixed
        /// neighbour order, so the same question always gets the same way.
        /// </summary>
        public static long[] Route(long fromX, long fromZ, long toX, long toZ) { return Route(fromX, fromZ, toX, toZ, 0, 0, 0); }

        /// <summary>
        /// The same way, keeping every cell centre further than <paramref name="avoidMm"/> from a point (the Aschbeter, who
        /// strikes from 2.12 m); the start and goal cells may lie inside that circle.
        /// </summary>
        public static long[] Route(long fromX, long fromZ, long toX, long toZ, long avoidX, long avoidZ, long avoidMm)
        {
            if (!CanStand(fromX, fromZ) || !CanStand(toX, toZ)) return new long[0];
            int start = Index(fromX, fromZ), goal = Index(toX, toZ);
            var previous = new int[Walk.Length];
            for (int i = 0; i < previous.Length; i++) previous[i] = -1;
            var queue = new int[Walk.Length];
            int head = 0, tail = 0;
            queue[tail++] = start; previous[start] = start;
            while (head < tail && previous[goal] < 0)
            {
                int cell = queue[head++], row = cell / Columns, column = cell %% Columns;
                for (int k = 0; k < 4; k++)
                {
                    int r = row + (k == 0 ? 1 : k == 1 ? -1 : 0), c = column + (k == 2 ? 1 : k == 3 ? -1 : 0);
                    if (r < 0 || c < 0 || r >= RowCount || c >= Columns) continue;
                    int next = r * Columns + c;
                    if (!Walk[next] || previous[next] >= 0) continue;
                    if (avoidMm > 0 && next != goal)
                    {
                        long dx = MinXmm + c * CellMm + CellMm / 2 - avoidX, dz = MinZmm + r * CellMm + CellMm / 2 - avoidZ;
                        long nextDistance = dx * dx + dz * dz;
                        if (nextDistance <= avoidMm * avoidMm)
                        {
                            long currentX = MinXmm + column * CellMm + CellMm / 2 - avoidX;
                            long currentZ = MinZmm + row * CellMm + CellMm / 2 - avoidZ;
                            // A player already inside can walk out. A path outside cannot cut back into the circle.
                            if (nextDistance <= currentX * currentX + currentZ * currentZ) continue;
                        }
                    }
                    previous[next] = cell; queue[tail++] = next;
                }
            }
            if (previous[goal] < 0) return new long[0];
            int length = 1;
            for (int cell = goal; cell != start; cell = previous[cell]) length++;
            var route = new long[length * 2];
            int at = length - 1;
            for (int cell = goal; ; cell = previous[cell], at--)
            {
                route[at * 2] = MinXmm + (cell %% Columns) * CellMm + CellMm / 2;
                route[at * 2 + 1] = MinZmm + (cell / Columns) * CellMm + CellMm / 2;
                if (cell == start) break;
            }
            return route;
        }

        private static int Index(long x, long z) { return (int)(FloorDiv(z - MinZmm, CellMm) * Columns + FloorDiv(x - MinXmm, CellMm)); }

        private static long Sample(long column, long row)
        {
            column = Math.Max(0, Math.Min(HeightColumns - 1, column));
            row = Math.Max(0, Math.Min(HeightRowCount - 1, row));
            return Height[row * HeightColumns + column] * HeightStepMm;
        }

        private static long FloorDiv(long value, long step) { return value >= 0 ? value / step : -((-value + step - 1) / step); }

        private static bool[] DecodeWalk()
        {
            if (WalkRows.Length != RowCount) throw new InvalidOperationException("Court walk rows corrupt");
            var cells = new bool[RowCount * Columns];
            for (int row = 0; row < RowCount; row++)
            {
                int column = 0, count = 0;
                foreach (char ch in WalkRows[row])
                {
                    if (ch >= '0' && ch <= '9') { count = checked(count * 10 + (ch - '0')); continue; }
                    if ((ch != '.' && ch != '#') || count == 0 || column + count > Columns) throw new InvalidOperationException("Court walk run corrupt");
                    for (int i = 0; i < count; i++) cells[row * Columns + column + i] = ch == '.';
                    column += count; count = 0;
                }
                if (column != Columns || count != 0) throw new InvalidOperationException("Court walk row width corrupt");
            }
            return cells;
        }

        private static byte[] DecodeHeights()
        {
            const string Alphabet = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";
            if (HeightRows.Length != HeightRowCount) throw new InvalidOperationException("Court height rows corrupt");
            var cells = new byte[HeightRowCount * HeightColumns];
            for (int row = 0; row < HeightRowCount; row++)
            {
                string line = HeightRows[row];
                if (line.Length != HeightColumns) throw new InvalidOperationException("Court height row width corrupt");
                for (int column = 0; column < HeightColumns; column++)
                {
                    int level = Alphabet.IndexOf(line[column]);
                    if (level < 0) throw new InvalidOperationException("Court height level corrupt");
                    cells[row * HeightColumns + column] = (byte)level;
                }
            }
            return cells;
        }

        private static readonly string[] WalkRows =
        {
%(walk)s
        };

        private static readonly string[] HeightRows =
        {
%(heights)s
        };
    }
}
''' % {"min_x": mm(r["min_x"]), "min_z": mm(r["min_z"]), "base": mm(r["height_base"]), "cols": r["cols"], "rows": r["rows"],
       "hcols": r["height_cols"], "hrows": r["height_rows"], "sx": mm(spawn[0]), "sz": mm(spawn[1]), "ex": mm(exit_[0]), "ez": mm(exit_[1]),
       "walk": walk, "heights": heights}
open(out, "w", encoding="utf-8").write(source)
print("written", out, len(source), "bytes")
